export function renderActionIcon(icon: ReactNode): ReactNode {
  if (!icon) return null;

  if (typeof icon === 'string') {
    const key = icon.toLowerCase().trim();
    if (key in iconAliasMap) {
      return ActionIcons[iconAliasMap[key]];
    }
    return <span>{icon}</span>;
  }

  return icon;
}
